import type {
  AccessibilityElement,
  AccessibilitySelector,
} from "@swipt/api/accessibility";

export type Rule = Exclude<
  AccessibilitySelector,
  (element: AccessibilityElement) => boolean
>;

const literal = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const words = (name: string) =>
  name
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .split(/[\s_-]+/)
    .filter(Boolean);
const skip = (...classes: string[]): Rule => ({
  class: new RegExp(`^(?:${classes.map(literal).join("|")})$`),
});
const label = (image: string) =>
  new RegExp(`^${words(image).map(literal).join("[\\s_-]*")}$`, "i");
const image = (name: string): Rule[] => [
  { identifier: name },
  { label: label(name) },
];

export interface Close extends Rule {
  swipe?: "left" | "right" | "up" | "down";
  large?: boolean;
}

// UIKit labels a button without a title by its image name.
const closeIn = (container: string, ...images: string[]): Close[] =>
  images.map((name) => ({ label: label(name), within: { class: container } }));

